package app.daltokki.drive.domain.dialog

/**
 * 달토끼가 지금 어떤 질문에 대한 대답을 기다리는지.
 * 자동 시연의 '자동 운전자'가 이것을 보고 대본대로 대답합니다(수동 시연·실사용에서는 화면 표시에만 쓰임).
 */
enum class ReplyContext {
    /** 출발 인사 질문 ("오늘 어디 가?") */
    GREETING,
    /** 출발 전 컨디션 ("어젯밤 몇 시간 잤어?") */
    SLEEP,
    /** 주의 단계 말 걸기 */
    CHECK_IN,
    /** 말 걸기에 대답이 없어 한 번 더 ("내 말 들려?") */
    CHECK_IN_RETRY,
    /** 경고 단계 "쉬어갈까, 반응 게임 할까?" */
    OFFER,
    /** "안 졸려" → "게임으로 증명해 볼래?" */
    AWAKE_CHALLENGE,
    /** 휴게소 경로 추가 여부 (응/아니) */
    REST,
    /** 끝말잇기 차례 */
    WORD,
    /** 퀴즈 답 */
    QUIZ,
    /** 반응 게임 "달!" → "빛!" */
    REACTION,
    /** "외기로 바꿔 줄까?" (응/아니) */
    FRESH_AIR,
    /** 휴게소에서 "커피냅 15분 할래?" (응/아니) */
    NAP,
    /** 지루함 예방 "말놀이 한 판 할래?" (응/아니) */
    BOREDOM,
    /** 초성 게임 답 */
    CHOSUNG,
    /** 휴게소 음식 퀴즈 답 */
    FOOD,
    /** 숫자 따라 말하기 */
    DIGITS,
    /** 수수께끼 답 */
    RIDDLE,
    /** "오늘도 부산 가?" (기억하는 대화) */
    MEMORY,
    /** "실내 온도 2도 낮춰 줄까?" (응/아니) */
    COOL_DOWN,
}
